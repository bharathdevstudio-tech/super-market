/* ============================================================================
   01_create_sync_queue.sql
   ----------------------------------------------------------------------------
   Adds a transactional outbox for offline-first sync to the EXISTING
   SQL Server 2008 R2 database.

   THIS SCRIPT IS PURELY ADDITIVE.
     - It creates new objects prefixed SM_Sync*.
     - It does NOT alter, drop or rename any existing table, column, index,
       trigger, view or stored procedure.
     - It does NOT touch tbl_SalDetail, tbl_SalParticular, tbl_PurchDetail,
       tbl_PurchParticular, tbl_MultiStock, tbl_StockDtl or tbl_StockModify.

   Safe to re-run: every object is created only if it does not already exist.

   Compatibility: SQL Server 2008 R2 (no OFFSET/FETCH, no MERGE, no THROW,
   no SEQUENCE, no HASHBYTES 'SHA2_256', no IIF, no CONCAT).

   Rollback: run 02_rollback_sync_queue.sql
   ============================================================================ */

SET NOCOUNT ON;
GO

/* ----------------------------------------------------------------------------
   1. SM_SyncOutbox - one row per document change event.

   Written INSIDE the same transaction that writes the bill, so a committed
   bill always has exactly one committed outbox row. A rolled-back bill leaves
   no outbox row.
   ---------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.SM_SyncOutbox', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SM_SyncOutbox
    (
        OutboxID          BIGINT           IDENTITY(1,1) NOT NULL,

        /* Idempotency key generated by the desktop app (Guid).
           The Worker uses it as X-Idempotency-Key, so a retried upload can
           never create a second cloud bill. */
        EventID           UNIQUEIDENTIFIER NOT NULL,

        /* 'SALE' | 'SALE_UPDATE' is carried in Operation; EntityType stays
           the document family so events for one bill sort together. */
        EntityType        VARCHAR(30)      NOT NULL,   -- SALE | PURCHASE
        EntityKey         VARCHAR(120)     NOT NULL,   -- Sa_InvNo_vc
        Operation         VARCHAR(10)      NOT NULL,   -- INSERT | UPDATE | DELETE

        /* Business identity of the document, duplicated out of the payload so
           the queue can be queried without parsing JSON on SQL Server 2008. */
        SaveType          VARCHAR(30)      NULL,       -- INVOICE | ESTIMATE | SALES RETURN ...
        AcYear            VARCHAR(20)      NULL,       -- e.g. 2026-2027
        BillNo            NUMERIC(18,0)    NULL,       -- Sa_BillNo_n

        PayloadVersion    INT              NOT NULL CONSTRAINT DF_SM_SyncOutbox_PayloadVersion DEFAULT (1),
        Payload           NVARCHAR(MAX)    NOT NULL,   -- UTF-8 JSON produced by the app

        /* SHA-256 hex of the exact payload bytes, computed in .NET
           (SQL 2008 R2 HASHBYTES only offers MD5/SHA1). Lets the Worker
           reject a body that was mangled in transit. */
        ContentHash       CHAR(64)         NOT NULL,

        StoreID           VARCHAR(50)      NOT NULL,   -- shop / device identity
        OccurredAtUtc     DATETIME         NOT NULL,   -- when the business event happened
        CreatedAtUtc      DATETIME         NOT NULL CONSTRAINT DF_SM_SyncOutbox_CreatedAtUtc DEFAULT (GETUTCDATE()),

        Status            VARCHAR(12)      NOT NULL CONSTRAINT DF_SM_SyncOutbox_Status DEFAULT ('PENDING'),
        AttemptCount      INT              NOT NULL CONSTRAINT DF_SM_SyncOutbox_AttemptCount DEFAULT (0),
        NextAttemptAtUtc  DATETIME         NOT NULL CONSTRAINT DF_SM_SyncOutbox_NextAttemptAtUtc DEFAULT (GETUTCDATE()),
        LastError         NVARCHAR(1000)   NULL,
        SentAtUtc         DATETIME         NULL,

        LockedBy          VARCHAR(100)     NULL,
        LockedAtUtc       DATETIME         NULL,

        CONSTRAINT PK_SM_SyncOutbox PRIMARY KEY CLUSTERED (OutboxID),
        CONSTRAINT CK_SM_SyncOutbox_Status
            CHECK (Status IN ('PENDING','SENDING','SENT','FAILED','DEAD')),
        CONSTRAINT CK_SM_SyncOutbox_Operation
            CHECK (Operation IN ('INSERT','UPDATE','DELETE'))
    );

    /* One row per event, forever. This is the idempotency guarantee. */
    ALTER TABLE dbo.SM_SyncOutbox
        ADD CONSTRAINT UQ_SM_SyncOutbox_EventID UNIQUE (EventID);
END
GO

/* Queue scan: "next batch of work" is the hot path. */
IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE name = N'IX_SM_SyncOutbox_Status_NextAttempt'
                 AND object_id = OBJECT_ID(N'dbo.SM_SyncOutbox'))
BEGIN
    CREATE INDEX IX_SM_SyncOutbox_Status_NextAttempt
        ON dbo.SM_SyncOutbox (Status, NextAttemptAtUtc)
        INCLUDE (EntityType, EntityKey, Operation);
END
GO

/* "what is the state of bill X?" and duplicate detection per document. */
IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE name = N'IX_SM_SyncOutbox_Entity'
                 AND object_id = OBJECT_ID(N'dbo.SM_SyncOutbox'))
BEGIN
    CREATE INDEX IX_SM_SyncOutbox_Entity
        ON dbo.SM_SyncOutbox (EntityType, EntityKey, OutboxID);
END
GO

/* ----------------------------------------------------------------------------
   2. SM_SyncOutboxLog - append-only attempt history.

   The outbox row keeps only the latest state; this keeps every attempt so a
   failure can be diagnosed after the fact instead of guessed at.
   ---------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.SM_SyncOutboxLog', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SM_SyncOutboxLog
    (
        LogID        BIGINT        IDENTITY(1,1) NOT NULL,
        OutboxID     BIGINT        NOT NULL,
        EventID      UNIQUEIDENTIFIER NOT NULL,
        AttemptNo    INT           NOT NULL,
        Result       VARCHAR(12)   NOT NULL,   -- CLAIMED | SENT | FAILED | DEAD
        HttpStatus   INT           NULL,
        Message      NVARCHAR(1000) NULL,
        LoggedAtUtc  DATETIME      NOT NULL CONSTRAINT DF_SM_SyncOutboxLog_LoggedAtUtc DEFAULT (GETUTCDATE()),

        CONSTRAINT PK_SM_SyncOutboxLog PRIMARY KEY CLUSTERED (LogID)
    );

    CREATE INDEX IX_SM_SyncOutboxLog_Outbox
        ON dbo.SM_SyncOutboxLog (OutboxID, LogID);
END
GO

/* ----------------------------------------------------------------------------
   3. SM_SyncMeta - small key/value store for sync bookkeeping.

   Examples: StoreID, DeviceName, LastSuccessfulSyncUtc, SyncEnabled.
   ---------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.SM_SyncMeta', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SM_SyncMeta
    (
        MetaKey      VARCHAR(50)   NOT NULL,
        MetaValue    NVARCHAR(500) NULL,
        UpdatedAtUtc DATETIME      NOT NULL CONSTRAINT DF_SM_SyncMeta_UpdatedAtUtc DEFAULT (GETUTCDATE()),

        CONSTRAINT PK_SM_SyncMeta PRIMARY KEY CLUSTERED (MetaKey)
    );
END
GO

/* ----------------------------------------------------------------------------
   4. SM_SyncOutbox_Claim - atomically take a batch of work.

   READPAST + UPDLOCK + ROWLOCK means two running copies of the app never pick
   the same row. Rows stuck in SENDING past @StaleMinutes (process crashed
   mid-upload) are reclaimed automatically.

   Returns the claimed rows as a result set.
   ---------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.SM_SyncOutbox_Claim', N'P') IS NOT NULL
    DROP PROCEDURE dbo.SM_SyncOutbox_Claim;
GO
CREATE PROCEDURE dbo.SM_SyncOutbox_Claim
    @WorkerId     VARCHAR(100),
    @BatchSize    INT = 50,
    @StaleMinutes INT = 10
AS
BEGIN
    SET NOCOUNT ON;

    IF @BatchSize IS NULL OR @BatchSize < 1 SET @BatchSize = 1;
    IF @BatchSize > 500 SET @BatchSize = 500;
    IF @StaleMinutes IS NULL OR @StaleMinutes < 1 SET @StaleMinutes = 10;

    ;WITH Claimable AS
    (
        SELECT TOP (@BatchSize) *
        FROM dbo.SM_SyncOutbox WITH (READPAST, UPDLOCK, ROWLOCK)
        WHERE (Status IN ('PENDING','FAILED') AND NextAttemptAtUtc <= GETUTCDATE())
           OR (Status = 'SENDING' AND LockedAtUtc < DATEADD(MINUTE, -@StaleMinutes, GETUTCDATE()))
        ORDER BY OutboxID
    )
    UPDATE Claimable
       SET Status       = 'SENDING',
           LockedBy     = @WorkerId,
           LockedAtUtc  = GETUTCDATE(),
           AttemptCount = AttemptCount + 1
    OUTPUT inserted.OutboxID,
           inserted.EventID,
           inserted.EntityType,
           inserted.EntityKey,
           inserted.Operation,
           inserted.SaveType,
           inserted.AcYear,
           inserted.BillNo,
           inserted.PayloadVersion,
           inserted.Payload,
           inserted.ContentHash,
           inserted.StoreID,
           inserted.OccurredAtUtc,
           inserted.AttemptCount
    ;
END
GO

/* ----------------------------------------------------------------------------
   5. SM_SyncOutbox_MarkSent - success.

   Guarded on Status='SENDING' so a duplicate completion (two threads, retry
   after timeout) is a no-op rather than a second state change.
   ---------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.SM_SyncOutbox_MarkSent', N'P') IS NOT NULL
    DROP PROCEDURE dbo.SM_SyncOutbox_MarkSent;
GO
CREATE PROCEDURE dbo.SM_SyncOutbox_MarkSent
    @OutboxID  BIGINT,
    @EventID   UNIQUEIDENTIFIER,
    @HttpStatus INT = NULL,
    @Message   NVARCHAR(1000) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE dbo.SM_SyncOutbox
       SET Status          = 'SENT',
           SentAtUtc       = GETUTCDATE(),
           LastError       = NULL,
           LockedBy        = NULL,
           LockedAtUtc     = NULL,
           NextAttemptAtUtc = GETUTCDATE()
     WHERE OutboxID = @OutboxID
       AND EventID  = @EventID
       AND Status   = 'SENDING';

    IF @@ROWCOUNT > 0
    BEGIN
        INSERT INTO dbo.SM_SyncOutboxLog
            (OutboxID, EventID, AttemptNo, Result, HttpStatus, Message)
        SELECT OutboxID, EventID, AttemptCount, 'SENT', @HttpStatus, @Message
        FROM dbo.SM_SyncOutbox WHERE OutboxID = @OutboxID;

        /* Record the watermark so the UI can say "last synced at ...". */
        IF EXISTS (SELECT 1 FROM dbo.SM_SyncMeta WHERE MetaKey = 'LastSuccessfulSyncUtc')
            UPDATE dbo.SM_SyncMeta
               SET MetaValue = CONVERT(VARCHAR(30), GETUTCDATE(), 126),
                   UpdatedAtUtc = GETUTCDATE()
             WHERE MetaKey = 'LastSuccessfulSyncUtc';
        ELSE
            INSERT INTO dbo.SM_SyncMeta (MetaKey, MetaValue)
            VALUES ('LastSuccessfulSyncUtc', CONVERT(VARCHAR(30), GETUTCDATE(), 126));
    END
END
GO

/* ----------------------------------------------------------------------------
   6. SM_SyncOutbox_MarkFailed - retry, or give up.

   The caller supplies the backoff it wants (exponential, computed in .NET) and
   the ceiling. Reaching the ceiling moves the row to DEAD so a single poison
   event cannot spin forever; DEAD rows are never claimed again but stay
   visible for manual inspection.
   ---------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.SM_SyncOutbox_MarkFailed', N'P') IS NOT NULL
    DROP PROCEDURE dbo.SM_SyncOutbox_MarkFailed;
GO
CREATE PROCEDURE dbo.SM_SyncOutbox_MarkFailed
    @OutboxID       BIGINT,
    @EventID        UNIQUEIDENTIFIER,
    @BackoffSeconds INT,
    @MaxAttempts    INT = 20,
    @HttpStatus     INT = NULL,
    @Message        NVARCHAR(1000) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    IF @BackoffSeconds IS NULL OR @BackoffSeconds < 0 SET @BackoffSeconds = 60;
    IF @MaxAttempts IS NULL OR @MaxAttempts < 1 SET @MaxAttempts = 20;
    IF @Message IS NOT NULL AND LEN(@Message) > 1000 SET @Message = LEFT(@Message, 1000);

    UPDATE dbo.SM_SyncOutbox
       SET Status = CASE WHEN AttemptCount >= @MaxAttempts THEN 'DEAD' ELSE 'FAILED' END,
           LastError       = @Message,
           NextAttemptAtUtc = DATEADD(SECOND, @BackoffSeconds, GETUTCDATE()),
           LockedBy        = NULL,
           LockedAtUtc     = NULL
     WHERE OutboxID = @OutboxID
       AND EventID  = @EventID
       AND Status   = 'SENDING';

    IF @@ROWCOUNT > 0
    BEGIN
        INSERT INTO dbo.SM_SyncOutboxLog
            (OutboxID, EventID, AttemptNo, Result, HttpStatus, Message)
        SELECT OutboxID, EventID, AttemptCount,
               CASE WHEN Status = 'DEAD' THEN 'DEAD' ELSE 'FAILED' END,
               @HttpStatus, @Message
        FROM dbo.SM_SyncOutbox WHERE OutboxID = @OutboxID;
    END
END
GO

/* ----------------------------------------------------------------------------
   7. SM_SyncOutbox_Stats - counts for the status bar / diagnostics screen.
   ---------------------------------------------------------------------------- */
IF OBJECT_ID(N'dbo.SM_SyncOutbox_Stats', N'P') IS NOT NULL
    DROP PROCEDURE dbo.SM_SyncOutbox_Stats;
GO
CREATE PROCEDURE dbo.SM_SyncOutbox_Stats
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        SUM(CASE WHEN Status = 'PENDING' THEN 1 ELSE 0 END) AS PendingCount,
        SUM(CASE WHEN Status = 'SENDING' THEN 1 ELSE 0 END) AS SendingCount,
        SUM(CASE WHEN Status = 'FAILED'  THEN 1 ELSE 0 END) AS FailedCount,
        SUM(CASE WHEN Status = 'DEAD'    THEN 1 ELSE 0 END) AS DeadCount,
        SUM(CASE WHEN Status = 'SENT'    THEN 1 ELSE 0 END) AS SentCount,
        COUNT(*)                                            AS TotalCount,
        /* Sentinel instead of NULL so 2008 R2 does not raise
           "Null value is eliminated by an aggregate"; NULLIF puts the NULL back. */
        NULLIF(MIN(CASE WHEN Status IN ('PENDING','FAILED')
                        THEN CreatedAtUtc
                        ELSE CONVERT(DATETIME, '9999-12-31') END),
               CONVERT(DATETIME, '9999-12-31'))               AS OldestUnsentUtc
    FROM dbo.SM_SyncOutbox;
END
GO

/* ----------------------------------------------------------------------------
   8. Seed the store identity if the shop has not set one yet.

   ProviderName is read from tbl_Companyprofile when present; otherwise a
   neutral placeholder is used. Nothing is overwritten if already set.
   ---------------------------------------------------------------------------- */
IF NOT EXISTS (SELECT 1 FROM dbo.SM_SyncMeta WHERE MetaKey = 'StoreID')
BEGIN
    INSERT INTO dbo.SM_SyncMeta (MetaKey, MetaValue)
    VALUES ('StoreID', 'STORE-1');
END
GO

IF NOT EXISTS (SELECT 1 FROM dbo.SM_SyncMeta WHERE MetaKey = 'SyncEnabled')
BEGIN
    /* Idle by default. Phase 3 flips this to 1 only after the capability check
       and the endpoint are configured, so existing behaviour is unchanged. */
    INSERT INTO dbo.SM_SyncMeta (MetaKey, MetaValue)
    VALUES ('SyncEnabled', '0');
END
GO

PRINT 'SM_Sync* objects created (additive; no existing object was modified).';
GO
